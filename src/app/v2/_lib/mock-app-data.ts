/** The athlete we simulate. A flagship city marathon gives a full ~24-week plan
 *  with every phase visible. Swap freely — all surfaces follow this one source. */
const DEMO_RACE_ID = "stockholm-marathon";

const DEMO_INPUT = {
  experience: "intermediate" as const,
  daysPerWeek: 5,
  weeklyKm: 42,
  longRunDay: 0, // Sunday
};

const DEMO_ATHLETE = { name: "Alex", experience: DEMO_INPUT.experience };

/** Resolves the demo onboarding input (race + profile) used to seed the in-app
 *  preview. Returns null if the demo race id can't be resolved. */
export function buildDemoPreviewInput(): PreviewInput | null {
  const race = getRaceById(DEMO_RACE_ID);
  if (!race) return null;
  return { race, ...DEMO_INPUT };
}

export interface AppSession extends PlannedSession {
  id: string;
  date: Date;
  weekNumber: number;
  phase: PlanPhase;
  isRecovery: boolean;
}

export interface AppWeek extends WeekPlan {
  weekStart: Date;
  weekEnd: Date;
  appSessions: AppSession[];
}

export interface AppPlan {
  race: Race;
  preview: PreviewResult;
  weeks: AppWeek[];
  raceDate: Date;
  planWeeks: number;
  thresholdPaceLabel: string;
  athlete: { name: string; experience: string };
}

/* ── date helpers (local, TZ-safe parse of 'yyyy-MM-dd') ──────────────────── */

function parseISODate(s: string): Date {
  const [y, m, d] = s.split("-").map(Number);
  return new Date(y, m - 1, d);
}
function addDays(d: Date, n: number): Date {
  const r = new Date(d);
  r.setDate(r.getDate() + n);
  return r;
}
/** dayOfWeek: 0=Sun..6=Sat. Weeks start Monday (weekStartsOn:1 in the engine). */
function offsetFromMonday(dayOfWeek: number): number {
  return dayOfWeek === 0 ? 6 : dayOfWeek - 1;
}

/* ── map a validated PreviewResult into the in-app AppPlan shape ───────────── */

export function buildAppPlan(
  result: PreviewResult,
  race: Race,
  athlete: { name: string; experience: string } = DEMO_ATHLETE,
): AppPlan {
  const weeks: AppWeek[] = result.weeks.map((w) => {
    const weekStart = parseISODate(w.startsOn);
    const weekEnd = addDays(weekStart, 6);
    const appSessions: AppSession[] = w.sessions.map((s) => ({
      ...s,
      id: `${w.weekNumber}-${s.dayOfWeek}-${s.orderInDay}`,
      date: addDays(weekStart, offsetFromMonday(s.dayOfWeek)),
      weekNumber: w.weekNumber,
      phase: w.phase,
      isRecovery: w.isRecovery,
    }));
    return { ...w, weekStart, weekEnd, appSessions };
  });

  return {
    race,
    preview: result,
    weeks,
    raceDate: result.raceDate,
    planWeeks: result.planWeeks,
    thresholdPaceLabel: result.thresholdPaceLabel,
    athlete,
  };
}

/* ── pure selectors over a provided AppPlan ───────────────────────────────── */

export function getAllSessions(plan: AppPlan): AppSession[] {
  return plan.weeks.flatMap((w) => w.appSessions);
}

export function getSessionById(
  plan: AppPlan,
  id: string,
): { session: AppSession; week: AppWeek } | null {
  for (const week of plan.weeks) {
    const session = week.appSessions.find((s) => s.id === id);
    if (session) return { session, week };
  }
  return null;
}

/** First session today or later (training types only — skips rest days). */
export function getNextSession(plan: AppPlan, from: Date = new Date()): AppSession | null {
  const start = new Date(from.getFullYear(), from.getMonth(), from.getDate());
  const upcoming = getAllSessions(plan)
    .filter((s) => s.type !== "rest" && s.date >= start)
    .sort((a, b) => a.date.getTime() - b.date.getTime());
  return upcoming[0] ?? null;
}

/** The week containing `from`, falling back to the first week. */
export function getCurrentWeek(plan: AppPlan, from: Date = new Date()): AppWeek {
  const hit = plan.weeks.find((w) => from >= w.weekStart && from <= addDays(w.weekEnd, 0.999));
  return hit ?? plan.weeks[0];
}

export function daysToRace(plan: AppPlan, from: Date = new Date()): number {
  return daysUntil(plan.raceDate, from);
}

