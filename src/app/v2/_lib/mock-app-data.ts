/** Deterministic pseudo-random so charts are stable between renders/builds. */
function seeded(seed: number): () => number {
  let s = seed % 2147483647;
  if (s <= 0) s += 2147483646;
  return () => (s = (s * 16807) % 2147483647) / 2147483647;
}

export interface FitnessPoint {
  weekLabel: string;
  ctl: number; // fitness (chronic load)
  atl: number; // fatigue (acute load)
  tsb: number; // form (CTL − ATL)
}

